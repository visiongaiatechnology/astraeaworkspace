// STATUS: DIAMANT VGT SUPREME — bounded fail-closed PDF/A-2b structural preflight.

export interface WriterPdfA2bPreflightReport {
  valid: boolean;
  checks: readonly string[];
  failures: readonly string[];
}

const MAX_ARCHIVE_BYTES = 512 * 1024 * 1024;

function decodeLatin1(bytes: Uint8Array): string {
  return new TextDecoder('latin1').decode(bytes);
}

function hasForbiddenFeature(pdf: string, token: RegExp): boolean {
  return token.test(pdf);
}

/**
 * Performs deterministic preflight over Writer's constrained PDF/A-2b emitter.
 * This is not a replacement for an independent ISO validator such as veraPDF;
 * it prevents Writer from labelling output PDF/A when mandatory material or a
 * known-forbidden construct is missing/present in the generated bytes.
 */
export function preflightWriterPdfA2b(bytes: Uint8Array): WriterPdfA2bPreflightReport {
  const checks: string[] = [];
  const failures: string[] = [];
  if (!(bytes instanceof Uint8Array) || bytes.byteLength < 256 || bytes.byteLength > MAX_ARCHIVE_BYTES) {
    return { valid: false, checks, failures: ['PDF/A byte-size boundary violation'] };
  }

  const pdf = decodeLatin1(bytes);
  const require = (condition: boolean, success: string, failure: string): void => {
    if (condition) checks.push(success);
    else failures.push(failure);
  };

  require(pdf.startsWith('%PDF-1.7\n'), 'PDF 1.7 header', 'PDF/A-2 requires a PDF 1.7 compatible file header');
  require(pdf.includes('xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/"'), 'PDF/A XMP namespace', 'PDF/A identification namespace missing');
  require(pdf.includes('<pdfaid:part>2</pdfaid:part>'), 'PDF/A part 2 declaration', 'PDF/A part declaration missing');
  require(pdf.includes('<pdfaid:conformance>B</pdfaid:conformance>'), 'PDF/A conformance B declaration', 'PDF/A conformance declaration missing');
  require(/\/Type\s*\/Metadata\s*\/Subtype\s*\/XML/u.test(pdf), 'XMP metadata stream', 'XMP metadata stream missing');
  require(/\/OutputIntents\s*\[/u.test(pdf), 'output intent reference', 'PDF/A output intent missing');
  require(/\/Type\s*\/OutputIntent\b/u.test(pdf) && /\/S\s*\/GTS_PDFA1\b/u.test(pdf), 'PDF/A output intent dictionary', 'PDF/A output intent dictionary invalid');
  require(/\/DestOutputProfile\s+\d+\s+0\s+R/u.test(pdf), 'ICC destination profile', 'ICC destination profile missing');
  require(/\/N\s+3\b/u.test(pdf) && /\/Alternate\s*\/DeviceRGB\b/u.test(pdf), 'RGB ICC profile declaration', 'RGB ICC profile declaration missing');
  require(/\/MarkInfo\s*<<\s*\/Marked\s+true\s*>>/u.test(pdf), 'tagged document marker', 'Tagged-PDF marker missing');
  require(/\/StructTreeRoot\s+\d+\s+0\s+R/u.test(pdf), 'structure tree', 'Structure tree missing');
  require(!/\/Type\s*\/Font\b/u.test(pdf), 'no unembedded font resources', 'Archive path emitted a font resource without an explicit embedding grant');
  require(!/(^|\s)(?:Tj|TJ)(?:\s|$)/mu.test(pdf), 'no raw text-show operators', 'Archive path emitted raw font text instead of shaped stencil content');
  require(/\/ActualText\s*</u.test(pdf), 'Unicode ActualText mapping', 'Unicode ActualText mapping missing');
  require(!hasForbiddenFeature(pdf, /\/Encrypt\b/u), 'not encrypted', 'PDF/A output must not be encrypted');
  require(!hasForbiddenFeature(pdf, /\/(?:JavaScript|JS|Launch|RichMedia|Movie)\b/u), 'no active-content actions', 'Active PDF content is forbidden in Writer PDF/A output');
  require(/startxref\s+\d+\s+%%EOF\s*$/u.test(pdf), 'xref/trailer terminator', 'PDF trailer/xref terminator missing');

  return { valid: failures.length === 0, checks, failures };
}

export function assertWriterPdfA2b(bytes: Uint8Array): WriterPdfA2bPreflightReport {
  const report = preflightWriterPdfA2b(bytes);
  if (!report.valid) throw new Error(`PDF/A-2b preflight failed: ${report.failures.join('; ')}`);
  return report;
}
