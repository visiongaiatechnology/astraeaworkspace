// STATUS: DIAMANT VGT SUPREME
// Astraea Grid bounded Structured-Table model.
//
// Thin, decision-only layer on top of the canonical table features: it answers
// "what happens to range, columns, formulas and formats if this range becomes a
// table / if a new record is added at the edge", without mutating the cell store
// it was given.

import type {
  GridCell,
  GridStructuredTable,
  GridTableColumn,
} from '../../../shared/contracts/grid/workspaceGrid';
import { toA1 } from '../formulas/formula';
import { translateFormulaReferences } from '../formulas/gridFormulaReferences';
import { parseGridRange } from '../compat/gridProfessional';
import { createStructuredTable } from '../tables/gridStructuredTables';

/** Bound on the cell count accepted for "range -> table". */
export const MAX_STRUCTURED_TABLE_CELLS = 100_000;
/** Bound on the accepted table-range rows (header + data + totals). */
export const MAX_STRUCTURED_TABLE_ROWS = 50_000;
/** Bound on the accepted header text length. */
export const MAX_TABLE_HEADER_LENGTH = 128;
/** Bound on expanded columns generated by one import. */
export const MAX_TABLE_AUTO_EXPAND_COLUMNS = 64;

export type StructuredTableErrorCode =
  | 'table_range_invalid'
  | 'table_range_too_large'
  | 'table_range_too_many_rows'
  | 'table_has_no_header_row'
  | 'table_overlaps_existing'
  | 'table_name_invalid'
  | 'table_expand_limit'
  | 'table_column_missing';

export interface StructuredTableIssue {
  readonly code: StructuredTableErrorCode;
  readonly detail: string;
}

export type StructuredTableResult<T> =
  | { readonly ok: true; readonly value: T }
  | { readonly ok: false; readonly issues: readonly StructuredTableIssue[] };

export interface TableColumnPreview {
  readonly name: string;
  readonly column: string;
  readonly totalFunction: NonNullable<GridTableColumn['totalFunction']>;
  /** Concrete, non-colour note about the inferred aggregation. */
  readonly note: string;
}

export interface StructuredTablePreview {
  readonly range: string;
  readonly name: string;
  readonly hasHeaders: boolean;
  readonly hasTotalsRow: boolean;
  readonly columns: readonly TableColumnPreview[];
  readonly dataRowCount: number;
  readonly cellCount: number;
  readonly headerTexts: readonly string[];
}

function columnLetterOf(index: number): string {
  return toA1(index, 0).replace(/\d+$/, '');
}

function boundedHeader(value: unknown, fallback: string): string {
  const text = String(value ?? '').trim();
  if (!text) return fallback;
  return text.length > MAX_TABLE_HEADER_LENGTH ? text.slice(0, MAX_TABLE_HEADER_LENGTH) : text;
}

function totalFormulaName(fn: GridTableColumn['totalFunction']): string | null {
  switch (fn) {
    case 'sum': return 'SUM';
    case 'count': return 'COUNT';
    case 'average': return 'AVERAGE';
    case 'min': return 'MIN';
    case 'max': return 'MAX';
    case 'stdDev': return 'STDEV.S';
    case 'var': return 'VAR.S';
    default: return null;
  }
}

/** Fail-closed range validation for "A1:D50 -> table". */
export function validateTableRange(range: string): readonly StructuredTableIssue[] {
  const issues: StructuredTableIssue[] = [];
  const bounds = parseGridRange(range.trim().toUpperCase());
  if (!bounds) {
    issues.push({ code: 'table_range_invalid', detail: range.slice(0, 64) });
    return issues;
  }
  const rows = bounds.endRow - bounds.startRow + 1;
  const cells = rows * (bounds.endCol - bounds.startCol + 1);
  if (rows < 2) {
    issues.push({ code: 'table_has_no_header_row', detail: `${rows} row(s)` });
  }
  if (rows > MAX_STRUCTURED_TABLE_ROWS) {
    issues.push({ code: 'table_range_too_many_rows', detail: `${rows} > ${MAX_STRUCTURED_TABLE_ROWS}` });
  }
  if (cells > MAX_STRUCTURED_TABLE_CELLS) {
    issues.push({ code: 'table_range_too_large', detail: `${cells} > ${MAX_STRUCTURED_TABLE_CELLS}` });
  }
  return issues;
}

/**
 * Computes exactly what "A1:D50 in Tabelle verwandeln" produces, without
 * touching the worksheet.
 */
export function previewStructuredTable(options: {
  range: string;
  cells: Readonly<Record<string, GridCell>>;
  existingTables: readonly GridStructuredTable[];
  sheetId: string;
  name?: string;
  hasHeaders?: boolean;
  hasTotalsRow?: boolean;
}): StructuredTableResult<{ table: GridStructuredTable; preview: StructuredTablePreview; updatedCells: Record<string, GridCell> }> {
  const issues = [...validateTableRange(options.range)];
  if (issues.length > 0) return { ok: false, issues };

  const hasHeaders = options.hasHeaders ?? true;
  if (!hasHeaders) {
    return { ok: false, issues: [{ code: 'table_has_no_header_row', detail: 'hasHeaders=false requires explicit column names' }] };
  }

  const bounds = parseGridRange(options.range.trim().toUpperCase());
  if (!bounds) return { ok: false, issues: [{ code: 'table_range_invalid', detail: options.range }] };

  const overlaps = options.existingTables.some((table) => {
    const other = parseGridRange(table.range);
    return !!other && !(bounds.endRow < other.startRow || bounds.startRow > other.endRow || bounds.endCol < other.startCol || bounds.startCol > other.endCol);
  });
  if (overlaps) return { ok: false, issues: [{ code: 'table_overlaps_existing', detail: options.range }] };

  let created: { table: GridStructuredTable; updatedCells: Record<string, GridCell> };
  try {
    created = createStructuredTable(
      {
        range: options.range.trim().toUpperCase(),
        ...(options.name ? { name: options.name } : {}),
        hasHeaders: true,
        hasTotalsRow: options.hasTotalsRow ?? false,
      },
      options.cells as Record<string, GridCell>,
      [...options.existingTables],
      options.sheetId,
    );
  } catch (error) {
    return { ok: false, issues: [{ code: 'table_name_invalid', detail: error instanceof Error ? error.message.slice(0, 96) : 'unknown' }] };
  }

  const columns: TableColumnPreview[] = created.table.columns.map((column, index) => ({
    name: column.name,
    column: columnLetterOf(bounds.startCol + index),
    totalFunction: column.totalFunction ?? 'none',
    note: column.totalFunction && column.totalFunction !== 'none'
      ? 'Summe moeglich: Spalte enthaelt Zahlen'
      : 'Keine Summe: Spalte enthaelt keinen Zahlenwert',
  }));

  const tableBounds = parseGridRange(created.table.range) ?? bounds;
  const dataRowCount = created.table.hasTotalsRow
    ? tableBounds.endRow - bounds.startRow - 1
    : tableBounds.endRow - bounds.startRow;

  return {
    ok: true,
    value: {
      table: created.table,
      updatedCells: created.updatedCells,
      preview: {
        range: created.table.range,
        name: created.table.name,
        hasHeaders: true,
        hasTotalsRow: created.table.hasTotalsRow,
        columns,
        dataRowCount: Math.max(0, dataRowCount),
        cellCount: (bounds.endRow - bounds.startRow + 1) * (bounds.endCol - bounds.startCol + 1),
        headerTexts: created.table.columns.map((column) => boundedHeader(column.name, column.name)),
      },
    },
  };
}

export interface TableRecordExpansion {
  readonly tables: readonly GridStructuredTable[];
  readonly cells: Record<string, GridCell>;
  /** Concrete report of what the new record changed. */
  readonly applied: readonly string[];
}

/**
 * Adds one record directly under a table and reports whether the table grew,
 * which formulas were extended and which formats were carried along.
 *
 * Totals rows are rebuilt here instead of through the canonical auto-expansion
 * path: that path treats the totals block as derived output and clears the user
 * label in its first cell, which would silently lose data written by the user.
 * `lastTotalsRow` carries the untouched totals block across the shift.
 */
export function addStructuredTableRecord(options: {
  table: GridStructuredTable;
  cells: Readonly<Record<string, GridCell>>;
  values: Readonly<Record<string, GridCell['value']>>;
  /** Column name -> style template copied onto the new record. */
  formatTemplate?: Readonly<Record<string, Partial<GridCell>>>;
}): StructuredTableResult<TableRecordExpansion> {
  const bounds = parseGridRange(options.table.range);
  if (!bounds) return { ok: false, issues: [{ code: 'table_range_invalid', detail: options.table.range }] };

  const columnCount = options.table.columns.length;
  if (columnCount > MAX_TABLE_AUTO_EXPAND_COLUMNS) {
    return { ok: false, issues: [{ code: 'table_expand_limit', detail: `${columnCount} columns` }] };
  }
  if (bounds.endCol - bounds.startCol + 1 < columnCount) {
    return { ok: false, issues: [{ code: 'table_column_missing', detail: `${columnCount} columns declared` }] };
  }
  if (bounds.endRow - bounds.startRow + 2 > MAX_STRUCTURED_TABLE_ROWS) {
    return { ok: false, issues: [{ code: 'table_expand_limit', detail: 'row limit reached' }] };
  }

  const hasTotals = options.table.hasTotalsRow;
  const dataEnd = hasTotals ? bounds.endRow - 1 : bounds.endRow;
  const newRow = dataEnd + 1;
  const oldTotalsRow = hasTotals ? bounds.endRow : -1;
  const newTotalsRow = hasTotals ? bounds.endRow + 1 : -1;
  const dataStartRow = options.table.hasHeaders ? bounds.startRow + 1 : bounds.startRow;

  // Everything the user owns is preserved; only the one row that becomes the new
  // totals row is written by this function.
  const cells: Record<string, GridCell> = { ...options.cells };
  const applied: string[] = [];

  // 1. Move the user-authored totals block down by one row.
  if (hasTotals) {
    for (let column = bounds.startCol; column <= bounds.endCol; column++) {
      const source = cells[toA1(column, oldTotalsRow)];
      const target = toA1(column, newTotalsRow);
      if (source === undefined) delete cells[target];
      else cells[target] = { ...source };
      delete cells[toA1(column, oldTotalsRow)];
    }
  }

  // 2. Write the new record, extending formulas and carrying formats forward.
  options.table.columns.forEach((column, index) => {
    const columnIndex = bounds.startCol + index;
    const coord = toA1(columnIndex, newRow);
    const raw = options.values[column.name];
    if (raw === undefined && options.formatTemplate?.[column.name] === undefined && !options.cells[toA1(columnIndex, dataEnd)]?.formula) {
      // A column without a value, without a template and without a formula stays empty.
      delete cells[coord];
      return;
    }
    const previous = options.cells[toA1(columnIndex, dataEnd)];
    const extendedFormula = previous?.formula ? translateFormulaReferences(previous.formula, 1, 0) : undefined;
    cells[coord] = {
      ...(options.formatTemplate?.[column.name] ?? {}),
      value: raw ?? previous?.value ?? '',
      ...(extendedFormula ? { formula: extendedFormula } : {}),
      ...(previous?.format ? { format: previous.format } : {}),
      ...(previous?.numberFormatCode ? { numberFormatCode: previous.numberFormatCode } : {}),
      ...(previous?.bold ? { bold: previous.bold } : {}),
      ...(previous?.background ? { background: previous.background } : {}),
      ...(previous?.text_color ? { text_color: previous.text_color } : {}),
    };
    if (extendedFormula) applied.push(`${column.name}: Formel ${extendedFormula} auf Zeile ${newRow + 1} erweitert`);
  });

  // 3. Rebuild the totals row: the user's first-cell label is kept, the aggregation
  //    cells get their formula extended over the new record.
  if (hasTotals) {
    for (let column = bounds.startCol; column <= bounds.endCol; column++) {
      const coord = toA1(column, newTotalsRow);
      const declared = options.table.columns[column - bounds.startCol];
      const existing = cells[coord];
      const fn = hasTotals ? totalFormulaName(declared?.totalFunction) : null;
      if (column === bounds.startCol) {
        cells[coord] = { ...(existing ?? {}), value: existing?.value ?? 'Total', formula: undefined, bold: true };
        continue;
      }
      cells[coord] = fn
        ? { ...(existing ?? {}), value: existing?.value ?? 0, formula: `=${fn}(${toA1(column, dataStartRow)}:${toA1(column, newRow)})`, bold: true }
        : { ...(existing ?? {}), value: existing?.value ?? '', formula: undefined, bold: true };
    }
    applied.push('Summenzeile wurde um eine Zeile nach unten verschoben');
  }

  // 4. Grow the table range so the new data row (and the shifted totals row) is
  //    covered, without ever shrinking the declared range.
  const endRow = hasTotals ? newTotalsRow : newRow;
  const tables: GridStructuredTable[] = [{
    ...options.table,
    range: `${toA1(bounds.startCol, bounds.startRow)}:${toA1(bounds.endCol, Math.max(bounds.endRow, endRow))}`,
  }];

  applied.unshift(`Bereich ${options.table.range} -> ${tables[0].range}`);
  applied.push('Formate der Spalten auf den neuen Datensatz uebernommen');

  return {
    ok: true,
    value: {
      tables,
      cells,
      applied,
    },
  };
}

/** Concrete summary used by the panel header and by tests. */
export function describeStructuredTable(preview: StructuredTablePreview): string {
  const numeric = preview.columns.filter((column) => column.totalFunction !== 'none').length;
  return `${preview.name}: ${preview.columns.length} Spalten, ${preview.dataRowCount} Datensaetze, ${numeric} numerische Spalte(n), ${preview.cellCount} Zellen`;
}
